const messages = { 'zh-CN': zhCN, 'en-US': enUS }

export type AppMessages = typeof zhCN

/** 由 localStorage 初值构造实例（读值守卫归 prefsStore；本函数接收已收窄的 locale） */
export function createAppI18n(locale: AppLocale = DEFAULT_LOCALE) {
  return createI18n({
    legacy: false,
    globalInjection: true,
    locale,
    fallbackLocale: DEFAULT_LOCALE,
    messages,
  })
}

/** 单例（main.ts 装配；prefsStore.setLang 切换时同步此引用） */
export const i18n = createAppI18n()

/** 切换界面语言（响应式，不刷新；持久化由 prefsStore 落 localStorage） */
export function setLocale(locale: AppLocale): void {
  i18n.global.locale.value = locale
}
